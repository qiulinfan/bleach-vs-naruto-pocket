#!/usr/bin/env python3
"""Convert BVN map SWFs and copy faces, BGM and configuration.

Writes (all ignored by Git):
  images/bvn/map/<id>/<layer>.png      bg, map, front, front_fix layers
  images/bvn/face/*.png                select / HUD / win faces
  audio/bvn/bgm/*.mp3                  stage and character music
  component_types/generated/BVNMaps.lua     layer offsets, bounds, floors, spawn points
  component_types/generated/BVNConfig.lua   fighter, assist and map lists and the select grid
The configuration comes from the GPL BleachVsNaruto repository
(git submodule external/BleachVsNaruto, or --config).
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import swfxml  # noqa: E402
from convert_bvn import ASSETS, CACHE, ROOT, ffdec, lua_val  # noqa: E402

LAYERS = ("bg", "map", "front", "front_fix")
LINES = ("line_left", "line_right", "line_bottom", "line_player_bottom", "p1", "p2")


def convert_map(path):
    mid = path.stem
    work = CACHE / ("map_" + mid)
    work.mkdir(parents=True, exist_ok=True)
    xml = work / "swf.xml"
    if not xml.exists():
        ffdec("-swf2xml", str(path), str(xml))
    swf = swfxml.Swf(str(xml))
    # Root timeline frame 1.
    dl = {}
    for t in swf.tags:
        ty = t.get("type")
        if ty in swfxml.PLACE_TAGS and t.get("placeFlagHasCharacter") == "true":
            dl[int(t.get("depth"))] = {"cid": t.get("characterId"), "m": swfxml.parse_matrix(t.find("matrix")), "name": t.get("name")}
        elif ty == "ShowFrameTag":
            break
    out = {"id": mid, "layers": {}}
    out_dir = ROOT / "images" / "bvn" / "map" / mid
    shutil.rmtree(out_dir, ignore_errors=True)
    out_dir.mkdir(parents=True)
    named = {o["name"]: o for o in dl.values() if o.get("name")}
    for name in LINES:
        if name in named:
            m = named[name]["m"]
            out[name] = [round(m[4], 1), round(m[5], 1)]
    if "floor" in named:
        f = named["floor"]
        floors = []
        if f["cid"] in swf.sprites:
            for child in swf.timeline(f["cid"])[0][0].values():
                r = swfxml.transform_rect(swfxml.mul(f["m"], child["m"]), swf.bounds(child["cid"]))
                if r:
                    floors.append([round(r[0], 1), round(r[2], 1), round(r[1], 1)])
        out["floors"] = floors
    # MapLayer.normalize hides the portal logos; render from a copy without them.
    render_swf = path
    xml_text = xml.read_text(encoding="utf-8")
    if 'name="logo4399"' in xml_text or 'name="logo_mine"' in xml_text:
        tree = ET.parse(xml)
        for parent in tree.getroot().iter():
            for t in list(parent):
                if t.get("type") == "TagStub" or t.get("name") in ("logo4399", "logo_mine"):
                    parent.remove(t)
        stripped = work / "nologo.xml"
        tree.write(stripped, encoding="utf-8")
        render_swf = work / "nologo.swf"
        if not render_swf.exists():
            ffdec("-xml2swf", str(stripped), str(render_swf))
    for name in LAYERS:
        if name not in named:
            continue
        o = named[name]
        cid = o["cid"]
        kind = "sprite" if cid in swf.sprites else "shape"
        tmp = work / ("layer2_" + name)
        if not tmp.exists():
            ffdec("-selectid", cid, "-format", "%s:png" % kind, "-export", kind, str(tmp), str(render_swf))
        pngs = sorted(tmp.rglob("*.png"), key=lambda p: int(re.sub(r"\D", "", p.stem) or 0))
        if not pngs:
            continue
        im = Image.open(pngs[0]).convert("RGBA")
        im.save(out_dir / (name + ".png"), optimize=True)
        r = swf.bounds(cid)
        x0, y0 = (r[0], r[1]) if r else (0, 0)
        m = o["m"]
        out["layers"][name] = {"img": "bvn/map/%s/%s.png" % (mid, name), "x": round(m[4] + x0 * m[0], 1),
                               "y": round(m[5] + y0 * m[3], 1), "sx": round(m[0], 4), "sy": round(m[3], 4),
                               "w": im.width, "h": im.height}
    print("[map %s] layers %s" % (mid, ",".join(out["layers"])), flush=True)
    return out


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--config", type=Path, default=ROOT / "external" / "BleachVsNaruto" / "shared" / "assets" / "assets" / "config")
    args = p.parse_args()
    gen = ROOT / "component_types" / "generated"
    gen.mkdir(parents=True, exist_ok=True)
    maps = [convert_map(f) for f in sorted((ASSETS / "map").glob("*.swf"))]
    (gen / "BVNMaps.lua").write_text("-- Generated by tools/convert_maps.py. Do not edit.\nBVNMaps = %s\n" %
                                     lua_val({m["id"]: m for m in maps}), encoding="utf-8")
    # Faces and music.
    for sub, dst in (("face", ROOT / "images" / "bvn" / "face"), ("bgm", ROOT / "audio" / "bvn" / "bgm")):
        shutil.rmtree(dst, ignore_errors=True)
        shutil.copytree(ASSETS / sub, dst)
    ui = ROOT / "images" / "bvn" / "ui"
    ui.mkdir(parents=True, exist_ok=True)
    shutil.copy(args.config.parents[3] / "title.png", ui / "title.png")
    for f in (ASSETS / "map").glob("*.png"):
        shutil.copy(f, ROOT / "images" / "bvn" / "map" / f.name)
    cfg = {}
    for name in ("fighter", "assist", "map"):
        cfg[name] = json.loads((args.config / (name + ".json")).read_text(encoding="utf-8"))
    sel = ET.parse(args.config / "select.xml").getroot()
    def rows(tag):
        node = sel.find(tag)
        return [[{"id": it.text.strip(), "more": [x for x in (it.get("moreFighter") or "").split(",") if x]}
                 for it in row.iter("item") if it.text and it.text.strip()] for row in node.iter("row")] if node is not None else []

    cfg["select"] = {"grid": rows("char_list"), "assists": rows("assist_list")}
    (gen / "BVNConfig.lua").write_text("-- Generated by tools/convert_maps.py from 5DPLAY's config. Do not edit.\nBVNConfig = %s\n" %
                                       lua_val(cfg), encoding="utf-8")
    print("maps %d" % len(maps))


if __name__ == "__main__":
    main()
